export function getConverter(slug: string): ConverterSummary | undefined {
  return converters.find((c) => c.slug === slug);
}

export function getConvertersForCategory(
  category: ConverterSummary["category"],
): ConverterSummary[] {
  return converters.filter((c) => c.category === category);
}

function normalizeTurkish(value: string): string {
  return value
    .toLocaleLowerCase("tr-TR")
    .replace(/ç/g, "c")
    .replace(/ğ/g, "g")
    .replace(/ı/g, "i")
    .replace(/ö/g, "o")
    .replace(/ş/g, "s")
    .replace(/ü/g, "u");
}

export function searchConverters(query: string): ConverterSummary[] {
  const q = normalizeTurkish(query.trim());
  if (!q) return converters;
  return converters.filter((c) => {
    const haystack = normalizeTurkish(
      [c.title, c.description, ...(c.keywords ?? [])].join(" "),
    );
    return haystack.includes(q);
  });
}

/** Dosya MIME türüne ya da uzantısına göre kabul eden araçları döndürür. */
export function getConvertersForFile(
  mimeType: string,
  extension: string,
): ConverterSummary[] {
  const ext = extension.toLowerCase();
  return converters.filter((c) =>
    c.accepts.some(
      (a) => a === mimeType || a.toLowerCase() === `.${ext}` || a === ext,
    ),
  );
}
